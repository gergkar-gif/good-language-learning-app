#!/usr/bin/env python3
"""Structural notes for a batch of track units (ES B1 latam, 2026-11-26).

    python scripts/latam_unit_notes.py <course> <level> <unit id> [<unit id> ...] [--out notes.md]

The B2 latam batches' unit notes were written by hand (ten minutes a batch): which lessons drill a
skill taught later, which have no grammar tag, no goal or checklist section, what each lesson's text
is about against its title. This prints those facts per unit and lesson, for the reviewer to add the
topic and facts paragraph to:

- lesson title, top-level goal, and whether it has `goal` / `checklist` sections;
- its text (story `title` and first sentence: a text about another lesson's topic shows here) and
  its grammar screen (file and title);
- the grammar skills its items are tagged with, each marked `LATER` (on the knowledge sheet's later
  list), `RETIRED` (not in skills/<lang>.json) or known, and `NO GRAMMAR TAG` when none;
- named speakers in dialogue items (only Carlos, Meg and their siblings may be named, by role);
- check-content findings by kind, and the unit's unmet-word count (`--with-hidden`).

Unit-level: orphan grammar screens (a `<prefix>-*-gr.json` no lesson references).
"""
import collections
import glob
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALLOWED = {"Carlos", "Meg", "Ana", "Andreas", "Lauren", "Kaylee"}


def load(p):
    p = ROOT / p
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def run(cmd):
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8").stdout


def sheet_skills(course, level, uid):
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / "s.md"
        run([sys.executable, "scripts/prior_knowledge.py", course, level, uid, "--out", str(out)])
        text = out.read_text(encoding="utf-8") if out.is_file() else ""
    known, later, part = set(), set(), None
    for line in text.splitlines():
        if line.startswith("## "):
            part = "known" if line.startswith("## Known grammar") else "later" if "later" in line.lower() or "hidden" in line.lower() else None
        for slug in re.findall(r"\(`([a-z0-9-]+)`", line):
            (known if part == "known" else later if part == "later" else set()).add(slug)
    return known, later


def items_of(d):
    if isinstance(d, list):
        return d
    return d.get("exercises") or d.get("items") or [] if d else []


def first_sentence(story):
    for p in (story or {}).get("paragraphs", []):
        t = p.get("text") if isinstance(p, dict) else p
        if t:
            return re.split(r"(?<=[.!?])\s", t.strip())[0][:160]
    return ""


def main():
    args = sys.argv[1:]
    out = None
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1]
        del args[i:i + 2]
    if len(args) < 3:
        sys.exit(__doc__)
    course, level, uids = args[0], args[1].lower(), args[2:]
    lang = course.split("-")[0]
    registry = set((load(f"skills/{lang}.json") or {}).get("skills", {}))
    units = {u["id"]: u for u in load(f"content/{course}/curriculum/units/{level}.json")}
    refs = set()
    for f in glob.glob(str(ROOT / f"content/{course}/lessons/**/*.json"), recursive=True):
        for s in json.loads(Path(f).read_text(encoding="utf-8")).get("sections", []):
            if s.get("ref"):
                refs.add(s["ref"])
    lines = [f"# Structural notes: {course} {level.upper()} {', '.join(uids)}",
             "", "Generated by scripts/latam_unit_notes.py; add topic and facts by hand.", ""]
    for uid in uids:
        u = units[uid]
        stems = u["stems"]
        known, later = sheet_skills(course, level, uid)
        cc = run([sys.executable, "scripts/check-content.py", course, level, uid])
        by_stem = collections.defaultdict(collections.Counter)
        for l in cc.splitlines():
            m = re.match(r"(ERROR|suspect)\s+(\S+)\s+(\S+)", l)
            if m:
                by_stem[m.group(3).split(".")[0]][m.group(2)] += 1
        total = re.search(r"(\d+) error\(s\), (\d+) suspect\(s\)", cc)
        um = run(["node", "scripts/unmet-words.js", course, level, "--stems", ",".join(stems), "--with-hidden"])
        try:
            unmet = len(json.loads(um[um.index("["):]))
        except ValueError:
            unmet = "?"
        prefix = stems[0].rsplit("-", 1)[0]
        orphans = [Path(g).name for g in sorted(glob.glob(str(ROOT / f"content/{course}/grammar/{level}/{prefix}-*-gr.json")))
                   if f"grammar/{level}/{Path(g).name}" not in refs]
        lines += [f"## {uid} ({' '.join(stems)})", "",
                  f"check-content {total.group(1)} / {total.group(2)}; unmet words {unmet}."
                  + (f" Orphan screens: {', '.join(orphans)}." if orphans else ""), ""]
        for s in stems:
            les = load(f"content/{course}/lessons/{level}/{s}.json") or {}
            secs = les.get("sections", [])
            types = {x["type"] for x in secs}
            story = next((x["ref"] for x in secs if x["type"] == "story" and x.get("ref")), None)
            screen = next((x["ref"] for x in secs if x["type"] == "grammar" and x.get("ref")), None)
            tags, speakers = collections.Counter(), collections.Counter()
            for ex in (x["ref"] for x in secs if x["type"] == "exercise-group" and x.get("ref")):
                for it in items_of(load(f"content/{course}/{ex}")):
                    for t in it.get("teaches") or []:
                        if not t.endswith("-vocab"):
                            tags[t] += 1
                    if isinstance(it.get("prompt"), list):
                        for turn in it["prompt"]:
                            if isinstance(turn, dict) and turn.get("speaker"):
                                speakers[turn["speaker"]] += 1
            marks = []
            for t, n in tags.most_common():
                flag = "RETIRED" if t not in registry else "LATER" if t in later and t not in known else ""
                marks.append(f"`{t}` {n}" + (f" **{flag}**" if flag else ""))
            st = load(f"content/{course}/{story}") if story else None
            gr = load(f"content/{course}/{screen}") if screen else None
            bad = sorted(k for k in speakers if k not in ALLOWED)
            lines += [f"- **{s}** \"{les.get('title', '')}\""
                      + ("" if "goal" in types else " · no goal section")
                      + ("" if "checklist" in types else " · no checklist"),
                      f"  - goal: {les.get('goal', '')}",
                      f"  - text: {Path(story).name if story else 'none'}"
                      + (f" \"{st.get('title', '')}\": {first_sentence(st)}" if st else ""),
                      f"  - screen: {Path(screen).name if screen else 'none'}" + (f" \"{gr.get('title', '')}\"" if gr else ""),
                      f"  - grammar tags: {', '.join(marks) or '**NO GRAMMAR TAG**'}",
                      ]
            if speakers:
                lines.append(f"  - speakers: {', '.join(f'{k} {v}' for k, v in speakers.most_common())}"
                             + (f" (**rename: {', '.join(bad)}**)" if bad else ""))
            if by_stem.get(s):
                lines.append(f"  - findings: {', '.join(f'{k} {v}' for k, v in by_stem[s].most_common())}")
        lines.append("")
    text = "\n".join(lines)
    if out:
        Path(out).write_text(text, encoding="utf-8")
        print(f"wrote {out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
